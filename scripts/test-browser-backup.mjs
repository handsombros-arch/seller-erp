import assert from 'node:assert/strict';
globalThis.location={origin:'https://seller-erp.vercel.app'};
const {allowedKey,envelope,validate,assertCompatible,summarize}=await import('../public/browser-backup.mjs');
const rows=[{'날짜':'2026-10-01','광고비':123.4,'클릭수':2},{'날짜':'','광고비':4},{'날짜':new Date('2026-09-01T00:00:00Z')}];
const data={settings:{exchange_processed:'["1"]',forecast_discontinued:'["sku"]'},records:[{key:'all',value:rows}]};
const backup=await envelope(data);
assert.deepEqual(await validate(JSON.parse(JSON.stringify(backup))),data);
const gzip=await new Response(new Blob([JSON.stringify(backup)]).stream().pipeThrough(new CompressionStream('gzip'))).blob();
const restored=await validate(JSON.parse(await new Response(gzip.stream().pipeThrough(new DecompressionStream('gzip'))).text()));
assert.deepEqual(restored,data);assert.equal(summarize(restored).records[0].rows,3);
assert.equal(summarize(restored).records[0].missingDate,1);
assert.equal(summarize(restored).records[0].cost,127.4);
await assert.rejects(validate({...backup,payload:backup.payload+' '}),/무결성/);
await assert.rejects(validate({...backup,origin:'https://elsewhere.example'}),/주소/);
assertCompatible({settings:{},records:[]},data);assertCompatible(data,data);
assert.throws(()=>assertCompatible({settings:{exchange_processed:'[]'},records:[]},data),/충돌/);
assert.throws(()=>assertCompatible({settings:{},records:[{key:'all',value:[]}]},data),/충돌/);
for(const key of ['sb-abc-auth-token','password','access_token','__proto__'])assert.equal(allowedKey(key),false);
await assert.rejects(validate(await envelope({...data,settings:{password:'secret'}})),/허용/);
await assert.rejects(validate(await envelope({...data,records:[...data.records,...data.records]})),/항목/);
console.log('PASS: lossless raw rows and dates, gzip roundtrip, integrity, origin, conflict protection, credential exclusion, duplicate-key rejection');
